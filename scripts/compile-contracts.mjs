import fs from "node:fs/promises";
import { readFileSync } from "node:fs";
import path from "node:path";
import solc from "solc";

const files = ["contracts/ConsentCraft.sol", "contract-tests/Receivers.sol"];
const sources = Object.fromEntries(await Promise.all(files.map(async file => [file, { content: await fs.readFile(file, "utf8") }])));
const settings = { optimizer: { enabled: true, runs: 200 }, evmVersion: "cancun", outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } } };
const output = JSON.parse(solc.compile(JSON.stringify({ language: "Solidity", sources, settings }), { import: file => {
  try { return { contents: readFileSync(path.join("node_modules", file), "utf8") }; } catch { return { error: `Import not found: ${file}` }; }
} }));
for (const error of output.errors || []) console[error.severity === "error" ? "error" : "warn"](error.formattedMessage);
if (output.errors?.some(error => error.severity === "error")) process.exit(1);
await fs.mkdir("artifacts", { recursive: true });
for (const file of files) for (const [name, contract] of Object.entries(output.contracts[file])) {
  await fs.writeFile(`artifacts/${name}.json`, JSON.stringify({ contractName: name, compiler: solc.version(), settings, abi: contract.abi, bytecode: `0x${contract.evm.bytecode.object}`, deployedBytecode: `0x${contract.evm.deployedBytecode.object}` }, null, 2) + "\n");
}
const contract = output.contracts[files[0]].ConsentCraft;
await fs.mkdir("lib/contracts", { recursive: true });
await fs.writeFile("lib/contracts/abi.ts", `// Generated by scripts/compile-contracts.mjs. Do not edit manually.\nexport const consentCraftAbi = ${JSON.stringify(contract.abi, null, 2)} as const;\n`);
console.log(`Compiled ConsentCraft with solc ${solc.version()}; generated ABI and deployment bytecode.`);
